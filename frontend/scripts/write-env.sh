#!/bin/sh
# Writes .env.local from an environment's Terraform outputs, so the frontend talks to that
# deployment. Usage: npm run env:dev (or env:prod). Needs AWS credentials that can read state.
set -eu

ENVIRONMENT="${1:?usage: write-env.sh dev|prod}"
FRONTEND_DIR="$(cd "$(dirname "$0")/.." && pwd)"
ROOT="$FRONTEND_DIR/../infrastructure/environments/$ENVIRONMENT"

[ -d "$ROOT" ] || { echo "No Terraform root at $ROOT" >&2; exit 1; }

out() { terraform -chdir="$ROOT" output -raw "$1"; }

# Read every value before writing, so a failed read can't leave a half-written file
API_URL="$(out api_endpoint)"
USER_POOL_ID="$(out cognito_user_pool_id)"
CLIENT_ID="$(out cognito_client_id)"
# TENANT_ID overrides the default storefront, e.g. TENANT_ID=tidewater npm run env:dev
TENANT_ID="${TENANT_ID:-$(out storefront_tenant_id)}"

cat > "$FRONTEND_DIR/.env.local" <<EOF
# Generated by scripts/write-env.sh from the $ENVIRONMENT Terraform outputs - safe to regenerate
NEXT_PUBLIC_API_URL=$API_URL
NEXT_PUBLIC_COGNITO_USER_POOL_ID=$USER_POOL_ID
NEXT_PUBLIC_COGNITO_CLIENT_ID=$CLIENT_ID
NEXT_PUBLIC_TENANT_ID=$TENANT_ID
EOF

echo "Wrote .env.local for $ENVIRONMENT ($API_URL, store $TENANT_ID). Restart npm run dev to pick it up."
